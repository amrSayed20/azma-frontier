import { NextRequest, NextResponse } from 'next/server';
import { join, basename } from 'path';
import { readFile, unlink } from 'fs/promises';
import { verifySession } from '@/src/authentication';
import { getDb, getVaultAsset } from '@/src/persistent-storage';
import { persistUploadedAsset } from '@/src/vault/vault-asset-upload-storage';
import { deriveAsset, mutationRejectionSpokenAr } from '@/src/vault/sovereign-asset-mutation';
import { SourceChamber, DerivationKind, isDerivable, isLegacyAsset } from '@/src/vault/sovereign-vault-types';
import {
  upscaleImageViaProvider,
  UPSCALE_SCALE_FACTOR,
  UPSCALE_FACTORS,
  imageEditingIsConfigured,
  ImageEditError,
  type UpscaleScaleFactor,
} from '@/src/core/sovereign-ai-integration/adapters/magic-hour-image-editing';
import { CapabilityTarget } from '@/src/core/sovereign-orchestrator/qiyamah-intent-types';

export const dynamic = 'force-dynamic';

const SESSION_COOKIE = 'azma_session';

/**
 * Where uploaded and generated bytes actually live.
 *
 * Read at CALL time, never into a module constant — see the note in the edit
 * route, where that exact mistake cost eight tests and would have looked for a
 * Creator's bytes in a directory holding none.
 */
function uploadsDir(): string {
  return process.env.UPLOADS_DIR ?? join(process.cwd(), 'public', 'uploads');
}

/** Resolve a sovereign storage address to the file on disk. */
function resolveOnDisk(secureStorageUri: string): string | null {
  const name = basename(secureStorageUri);
  if (!name || name === '.' || name === '..') return null;
  if (secureStorageUri.startsWith('/generated-assets/')) {
    return join(uploadsDir(), 'generated-assets', name);
  }
  if (secureStorageUri.startsWith('/uploads/')) {
    return join(uploadsDir(), name);
  }
  // An address this route cannot read is refused rather than guessed at.
  return null;
}

function extensionOf(uri: string): string {
  const name = basename(uri);
  const dot = name.lastIndexOf('.');
  return dot === -1 ? '' : name.slice(dot);
}

/**
 * POST /api/vault/assets/[assetId]/upscale
 *
 * ─── WHY THIS IS MODIFIED AND NOT A NEW DERIVATION KIND ─────────────────────
 *
 *   An upscale does not change what the picture is — `preserve` mode exists
 *   precisely so it invents nothing — so calling it MODIFIED looked at first
 *   like recording a falsehood, and a new kind looked warranted.
 *
 *   It is not. The constitutional axis is «القيامة مسؤولة عن داخل الأصل، لا
 *   عن العلاقة الزمنية بين الأصول» (Five-Chamber Constitution, line 173).
 *   MODIFIED is the family «changed inside an existing asset, has a parent»,
 *   and an upscale is inside the asset and stays a still — ANIMATED is
 *   separate only because it crosses from stillness into motion. What was
 *   actually done is carried truthfully in `instructionAr`, so the lineage
 *   states the operation, not a guess at it. No constitutional change.
 *
 *   Every guard here is the edit route's, for the same reasons: ownership that
 *   cannot be probed, a legacy parent that must be adopted first, bytes read
 *   from disk before the engine is called, the provider never named to the
 *   Creator, and no orphaned bytes left behind when the derivation is refused.
 */
export async function POST(
  request: NextRequest,
  context: { params: Promise<{ assetId: string }> },
) {
  const sessionId = request.cookies.get(SESSION_COOKIE)?.value;
  const session = sessionId ? verifySession(sessionId) : null;
  if (!session) {
    return NextResponse.json(
      { status: 'failed', reason: 'unauthorized', message: 'سجّل دخولك أوّلاً.' },
      { status: 401 },
    );
  }

  const { assetId } = await context.params;

  if (!imageEditingIsConfigured()) {
    // The ability is never offered blind.
    return NextResponse.json(
      { status: 'failed', reason: 'capability-unavailable', message: 'رفع الدقّة غير متاحٍ حالياً.' },
      { status: 503 },
    );
  }

  // ── WHICH FACTOR, AND WHETHER IT MAY BE SOLD YET ─────────────────────────
  //
  //   4× is a real capability: the endpoint takes `scale_factor: 4`, the
  //   provider documents it for Creator tier and above, and this account's
  //   tier was read live. What does NOT exist is a Creator-facing price for
  //   it — `UPSCALE_2X` prices 2× and nothing prices 4×.
  //
  //   So the door accepts the choice and refuses to EXECUTE an unpriced one,
  //   with a reason in the Creator's own language. Deriving «four times the
  //   charge, so four times the price» would be setting a price, which is the
  //   Chief Architect's act and not this route's.
  let body: unknown = null;
  try { body = await request.json(); } catch { body = null; }
  const asked = (body as { scaleFactor?: unknown } | null)?.scaleFactor;
  const scaleFactor: UpscaleScaleFactor = asked === 4 ? 4 : UPSCALE_SCALE_FACTOR;
  const factorRecord = UPSCALE_FACTORS.find((f) => f.factor === scaleFactor);
  if (asked !== undefined && asked !== 2 && asked !== 4) {
    return NextResponse.json(
      { status: 'failed', reason: 'unknown-factor', message: 'المحرّكُ يَقبل مضاعفةً أو أربعاً فقط.' },
      { status: 400 },
    );
  }
  if (!factorRecord?.creatorPriceExists) {
    return NextResponse.json(
      {
        status: 'failed',
        reason: 'not-priced',
        message: 'رفعُ الدقّة أربعَ مرّاتٍ مبنيٌّ ولم يُسعَّر لك بعد. ولن يُنفَّذ قبل أن '
          + 'تَعرف ما يُكلّفك بالضبط.',
      },
      { status: 409 },
    );
  }

  // ── The asset, and the right to build on it ──────────────────────────────
  const db = getDb();
  const parent = getVaultAsset(db, assetId);
  if (!parent || parent.subscriberTenantId !== session.creatorId) {
    // Absent and not-yours answer alike, so ownership cannot be probed.
    return NextResponse.json(
      { status: 'failed', reason: 'not-found', message: 'الأصل غير موجود.' },
      { status: 404 },
    );
  }

  if (parent.capabilityTarget !== CapabilityTarget.VISUAL) {
    return NextResponse.json(
      { status: 'failed', reason: 'not-an-image', message: 'هذا الأصل ليس صورة.' },
      { status: 400 },
    );
  }

  if (isLegacyAsset(parent) && !isDerivable(parent)) {
    return NextResponse.json(
      {
        status: 'failed',
        reason: 'requires-adoption',
        message: mutationRejectionSpokenAr('PARENT_REQUIRES_ADOPTION'),
      },
      { status: 409 },
    );
  }
  if (!isDerivable(parent)) {
    return NextResponse.json(
      { status: 'failed', reason: 'not-derivable', message: mutationRejectionSpokenAr('PARENT_NOT_DERIVABLE') },
      { status: 409 },
    );
  }

  // ── Its bytes ────────────────────────────────────────────────────────────
  const diskPath = resolveOnDisk(parent.secureStorageUri);
  if (!diskPath) {
    return NextResponse.json(
      { status: 'failed', reason: 'source-unreadable', message: 'تعذّر الوصول إلى هذه الصورة.' },
      { status: 400 },
    );
  }

  let parentBytes: Buffer;
  try {
    parentBytes = await readFile(diskPath);
  } catch {
    // The storage path is never echoed to the Creator.
    console.error('[ImageUpscale] source unreadable for asset', assetId);
    return NextResponse.json(
      { status: 'failed', reason: 'source-unreadable', message: 'تعذّر قراءة الصورة الأصلية.' },
      { status: 500 },
    );
  }

  // ── The refinement itself, on the declared sovereign engine ──────────────
  let produced;
  try {
    produced = await upscaleImageViaProvider(
      parentBytes, extensionOf(parent.secureStorageUri), { scaleFactor });
  } catch (err) {
    // The engine's own words stay server-side; they name a provider.
    console.error('[ImageUpscale] engine failed:', err);
    const rejection = err instanceof ImageEditError ? err.rejection : null;
    if (rejection === 'NO_CREDIT') {
      return NextResponse.json(
        {
          status: 'failed',
          reason: 'capability-unavailable',
          message: 'رفع الدقّة متوقّفٌ مؤقّتاً لنفاد رصيد الإمبراطوريّة. لا شأن لصورتك بذلك.',
        },
        { status: 503 },
      );
    }
    if (rejection === 'TIMED_OUT') {
      return NextResponse.json(
        { status: 'failed', reason: 'timed-out', message: 'استغرق رفع الدقّة وقتاً طويلاً. أعد المحاولة.' },
        { status: 504 },
      );
    }
    return NextResponse.json(
      { status: 'failed', reason: 'upscale-failed', message: 'تعذّر رفع الدقّة. لم يُحفظ شيء.' },
      { status: 502 },
    );
  }

  // ── Write the result, then prove it earned its place ─────────────────────
  const persisted = await persistUploadedAsset(
    produced.bytes,
    produced.mimeType === 'image/jpeg' ? '.jpg' : '.png',
  );

  const outcome = await deriveAsset({
    parentAssetId: parent.assetId,
    ownerId: session.creatorId,
    parentBytes,
    outputBytes: produced.bytes,
    outputStorageUri: persisted.assetUrl,
    // Article 3.1: what happens inside an asset belongs to Qiyamah.
    chamber: SourceChamber.QIYAMAH,
    derivation: DerivationKind.MODIFIED,
    // The lineage states the operation plainly, so MODIFIED never has to be
    // interpreted as «the subject changed» when it did not.
    instructionAr: `رفع الدقّة ${UPSCALE_SCALE_FACTOR}× مع الحفاظ على الأصل دون إضافة تفاصيل`,
    operationId: persisted.assetId,
    actorId: session.creatorId,
    providerProvenance: {
      providerId: produced.providerId,
      providerModelId: produced.providerModelId,
      providerJobId: produced.providerJobId,
      // The provider's own charge for this operation. The adapter has always
      // returned it; nothing ever read it.
      creditsCharged: produced.creditsCharged,
      creditUnit: 'magic-hour-credits',
    },
  });

  if (!outcome.ok) {
    // NO ORPHAN. The bytes were written a moment ago and are now unreferenced.
    try { await unlink(join(uploadsDir(), basename(persisted.assetUrl))); } catch { /* already gone */ }

    const conflict = outcome.rejection === 'OUTPUT_IDENTICAL_TO_PARENT';
    return NextResponse.json(
      { status: 'failed', reason: outcome.rejection, message: mutationRejectionSpokenAr(outcome.rejection) },
      { status: conflict ? 409 : 400 },
    );
  }

  // The sovereign asset, never a storage path. Article 6.
  return NextResponse.json({
    status: 'succeeded',
    asset: outcome.asset,
    lineage: {
      parentAssetId: outcome.asset.parentAssetId,
      rootAssetId: outcome.asset.rootAssetId,
      version: outcome.asset.version,
    },
  });
}
