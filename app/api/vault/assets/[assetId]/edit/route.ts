export const dynamic = 'force-dynamic';

const SESSION_COOKIE = 'azma_session';
const MAX_INSTRUCTION = 1_000;

/**
 * Where uploaded and generated bytes actually live.
 *
 * NOT `public/<uri>`. In production UPLOADS_DIR is /var/www/azma-uploads and
 * `public/` holds nothing — the voice-cloning route resolves paths that way and
 * would fail to read a single asset on the live server. That latent bug is not
 * repeated here; this follows the delete route, which resolves correctly.
 */
function uploadsDir(): string {
  // Read at CALL time, never at import time.
  //
  // Written first as a module-level `const`, which froze the value the moment
  // Node imported this file. Anything that set the variable afterwards — a
  // test, a worker configured after load — was ignored, and the route then
  // looked for a Creator's bytes in a directory that held none and answered
  // 500. Eight tests failed on that one line.
  //
  // The same mistake was diagnosed and fixed in db.ts two phases earlier, and
  // then made again here in the same week. The lesson is not "remember" — it is
  // that an environment variable read into a module constant is a latent bug by
  // construction, so it is read through a function.
  return process.env.UPLOADS_DIR ?? join(process.cwd(), 'public', 'uploads');
}

/** Resolve a sovereign storage address to the file on disk. */
function resolveOnDisk(secureStorageUri: string): string | null {
  const name = basename(secureStorageUri);
  if (!name || name === '.' || name === '..') return null;
  if (secureStorageUri.startsWith('/generated-assets/')) {
    return join(uploadsDir(), 'generated-assets', name);
  }
  if (secureStorageUri.startsWith('/uploads/')) {
    return join(uploadsDir(), name);
  }
  // A provider-hosted or otherwise non-local asset. Editing needs the bytes,
  // and an address this route cannot read is refused rather than guessed at.
  return null;
}

function extensionOf(uri: string): string {
  const name = basename(uri);
  const dot = name.lastIndexOf('.');
  return dot === -1 ? '' : name.slice(dot);
}

/**
 * POST /api/vault/assets/[assetId]/edit
 *
 * ─── WHAT THIS ROUTE IS ─────────────────────────────────────────────────────
 *
 *   The join that was missing. Every piece existed and none of them touched:
 *   the Vault could list an asset, the engine could edit an image, and
 *   `deriveAsset` could record a lineage — but nothing called the second, and
 *   nothing called the third. A capability nobody can invoke is not a
 *   capability.
 *
 *   Constitution Article 3.1 — editing inside an asset is QIYAMAH's. This route
 *   records that chamber and never touches a timeline, an order or a
 *   transition, which belong to Ras Al Amr.
 *
 * ─── THE ORDER, WHICH IS THE SAFETY ─────────────────────────────────────────
 *
 *   session → own the asset → it is an image → it may be derived from →
 *   read its bytes → edit → write the result → prove the result differs →
 *   deposit.
 *
 *   The proof of difference happens in `deriveAsset`, AFTER the result is
 *   written and BEFORE it becomes an asset. If it refuses — the engine replayed
 *   its input, or the edit changed nothing — the file just written is removed.
 *   Article 6 forbids leaving an orphan, and an orphan is exactly what a
 *   refusal would otherwise leave on disk.
 */
export async function POST(
  request: NextRequest,
  context: { params: Promise<{ assetId: string }> },
) {
  const sessionId = request.cookies.get(SESSION_COOKIE)?.value;
  const session = sessionId ? verifySession(sessionId) : null;
  if (!session) {
    return NextResponse.json(
      { status: 'failed', reason: 'unauthorized', message: 'سجّل دخولك أوّلاً.' },
      { status: 401 },
    );
  }

  const { assetId } = await context.params;

  let body: unknown;
  try { body = await request.json(); } catch {
    return NextResponse.json(
      { status: 'failed', reason: 'invalid-input', message: 'الطلب غير صالح.' },
      { status: 400 },
    );
  }

  const instruction = typeof (body as { instruction?: unknown })?.instruction === 'string'
    ? ((body as { instruction: string }).instruction).trim()
    : '';

  if (instruction.length === 0) {
    return NextResponse.json(
      { status: 'failed', reason: 'empty-instruction', message: 'اكتب ما تريد تغييره في الصورة.' },
      { status: 400 },
    );
  }
  if (instruction.length > MAX_INSTRUCTION) {
    return NextResponse.json(
      { status: 'failed', reason: 'instruction-too-long', message: 'الوصف أطول من المسموح.' },
      { status: 400 },
    );
  }

  if (!imageEditingIsConfigured()) {
    // The ability is never offered blind. A Creator is told it is unavailable
    // rather than shown a failure that looks like their own mistake.
    return NextResponse.json(
      { status: 'failed', reason: 'capability-unavailable', message: 'تعديل الصور غير متاحٍ حالياً.' },
      { status: 503 },
    );
  }

  // ── The asset, and the right to build on it ──────────────────────────────
  const db = getDb();
  const parent = getVaultAsset(db, assetId);
  if (!parent || parent.subscriberTenantId !== session.creatorId) {
    // Absent and not-yours answer alike, so ownership cannot be probed.
    return NextResponse.json(
      { status: 'failed', reason: 'not-found', message: 'الأصل غير موجود.' },
      { status: 404 },
    );
  }

  if (parent.capabilityTarget !== CapabilityTarget.VISUAL) {
    return NextResponse.json(
      { status: 'failed', reason: 'not-an-image', message: 'هذا الأصل ليس صورة.' },
      { status: 400 },
    );
  }

  if (isLegacyAsset(parent) && !isDerivable(parent)) {
    return NextResponse.json(
      {
        status: 'failed',
        reason: 'requires-adoption',
        message: mutationRejectionSpokenAr('PARENT_REQUIRES_ADOPTION'),
      },
      { status: 409 },
    );
  }
  if (!isDerivable(parent)) {
    return NextResponse.json(
      { status: 'failed', reason: 'not-derivable', message: mutationRejectionSpokenAr('PARENT_NOT_DERIVABLE') },
      { status: 409 },
    );
  }

  // ── Its bytes ────────────────────────────────────────────────────────────
  const diskPath = resolveOnDisk(parent.secureStorageUri);
  if (!diskPath) {
    return NextResponse.json(
      { status: 'failed', reason: 'source-unreadable', message: 'تعذّر الوصول إلى هذه الصورة.' },
      { status: 400 },
    );
  }

  let parentBytes: Buffer;
  try {
    parentBytes = await readFile(diskPath);
  } catch {
    // The storage path is never echoed to the Creator.
    console.error('[ImageEdit] source unreadable for asset', assetId);
    return NextResponse.json(
      { status: 'failed', reason: 'source-unreadable', message: 'تعذّر قراءة الصورة الأصلية.' },
      { status: 500 },
    );
  }

  // ── The edit itself. Qiyamah's work, on the declared sovereign engine ─────
  let produced;
  try {
    produced = await editImageViaProvider(parentBytes, extensionOf(parent.secureStorageUri), instruction);
  } catch (err) {
    // The engine's own words stay server-side; they name a provider.
    console.error('[ImageEdit] engine failed:', err);
    // Each cause is told apart, because a Creator who is told "it failed" when
    // the truth is "the Empire is out of credit" will retry forever and blame
    // their own image. The engine is never named in any of them.
    const rejection = err instanceof ImageEditError ? err.rejection : null;
    if (rejection === 'NO_CREDIT') {
      return NextResponse.json(
        {
          status: 'failed',
          reason: 'capability-unavailable',
          message: 'تعديل الصور متوقّفٌ مؤقّتاً لنفاد رصيد الإمبراطوريّة. لا شأن لصورتك بذلك.',
        },
        { status: 503 },
      );
    }
    if (rejection === 'TIMED_OUT') {
      return NextResponse.json(
        { status: 'failed', reason: 'timed-out', message: 'استغرق التعديل وقتاً طويلاً. أعد المحاولة.' },
        { status: 504 },
      );
    }
    return NextResponse.json(
      { status: 'failed', reason: 'edit-failed', message: 'تعذّر تنفيذ التعديل. لم يُحفظ شيء.' },
      { status: 502 },
    );
  }

  // ── Write the result, then prove it earned its place ─────────────────────
  const persisted = await persistUploadedAsset(
    produced.bytes,
    produced.mimeType === 'image/jpeg' ? '.jpg' : '.png',
  );

  const outcome = await deriveAsset({
    parentAssetId: parent.assetId,
    ownerId: session.creatorId,
    parentBytes,
    outputBytes: produced.bytes,
    outputStorageUri: persisted.assetUrl,
    // Article 3.1: modification inside an asset belongs to Qiyamah.
    chamber: SourceChamber.QIYAMAH,
    derivation: DerivationKind.MODIFIED,
    instructionAr: instruction,
    operationId: persisted.assetId,
    actorId: session.creatorId,
  });

  if (!outcome.ok) {
    // NO ORPHAN. The bytes were written a moment ago and are now unreferenced;
    // they are removed before the refusal is returned.
    try { await unlink(join(uploadsDir(), basename(persisted.assetUrl))); } catch { /* already gone */ }

    const conflict = outcome.rejection === 'OUTPUT_IDENTICAL_TO_PARENT';
    return NextResponse.json(
      { status: 'failed', reason: outcome.rejection, message: mutationRejectionSpokenAr(outcome.rejection) },
      { status: conflict ? 409 : 400 },
    );
  }

  // The sovereign asset, never a storage path. Article 6.
  return NextResponse.json({
    status: 'succeeded',
    asset: outcome.asset,
    lineage: {
      parentAssetId: outcome.asset.parentAssetId,
      rootAssetId: outcome.asset.rootAssetId,
      version: outcome.asset.version,
    },
  });
}
